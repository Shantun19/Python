# Addition operators
print(10 + 20) # 30

# Subtraction
print(30 - 15) # 15

# Multiplication
print(10 * 10) # 100

# Division
print(15 / 2) # its returns the floating point value - 7.5

# Floor Division
print(15 // 2) # 7

# Modulus
print(15 % 2) # return the remainder - 1

# Exponentiation
print(5 ** 2) # 25