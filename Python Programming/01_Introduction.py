# 1. What happens when you write Python code?
# --------------------------------------------
#
# Suppose you write:
#
# name = "Vikas"
# print("Hello", name)
#
# This is written in a language that humans can understand
# fairly easily.
#
# But your computer's CPU does not understand Python directly.
# The CPU ultimately understands machine instructions.
#
# So, we need something that can take your Python code and make
# the computer execute it.
#
# That's where Python itself (the Python interpreter/runtime)
# comes in.
#
#
# When you install Python, you're installing a collection of
# things. One of the most important components is the:
#
# Python Interpreter
# ------------------
#
# - The interpreter is the program that reads and executes
#   Python code.
#
# - The basic flow is:
#
#   Python Code
#       ↓
#   Python Interpreter
#       ↓
#   Computer executes instructions
#       ↓
#   Output
#
# The interpreter is essentially the software that knows how
# to understand and execute Python code.